describe.each(Object.entries(REFERENCE))('%s matches the reviewed spec', (id, widths) => {
  it.each(Object.entries(widths))('at w=%s', (w, expected) => {
    const width = Number(w);
    const band = bandHeightFor(width);
    const { shapes } = planFor(getGridBannerOption(id), getGrid(width));
    expect(shapes).toHaveLength(expected.length);
    expected.forEach(([x, wd, h], i) => {
      expect(Math.abs(shapes[i].x - x), `shape ${i} x`).toBeLessThan(0.06);
      expect(Math.abs(shapes[i].width - wd), `shape ${i} width`).toBeLessThan(0.06);
      if (h !== undefined) expect(Math.abs((shapes[i].height ?? band) - h), `shape ${i} height`).toBeLessThan(0.06);
    });
  });
});
